const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),Module=require('node:module');
const root=path.join(__dirname,'..'),file=path.join(root,'src/lib/payout-policy.ts');
const swc=require(path.join(root,'node_modules/next/dist/build/swc'));
const m=new Module(file);m._compile(swc.transformSync(fs.readFileSync(file,'utf8'),{filename:file,jsc:{parser:{syntax:'typescript'},target:'es2020'},module:{type:'commonjs'}}).code,file);
const {refundAmounts,completedPayoutStatus,adminPayoutApproved,payoutApprovalMarker,customerCanDispute,payoutWindowOpen,disputeDeadline,DISPUTE_WINDOW_MS,reviewDateLabel}=m.exports;
const legacy={paidPence:50000,refundedPence:0,platformFeePence:2500};
const first=refundAmounts(legacy,25000);assert.deepEqual(first,{refundedPence:25000,platformFeePence:1250,transporterProceedsPence:23750});
const second=refundAmounts({...legacy,...first},10000);assert.equal(second.platformFeePence,750);assert.equal(second.transporterProceedsPence,14250);
assert.equal(refundAmounts({...legacy,...first},25000).transporterProceedsPence,0);
assert.throws(()=>refundAmounts(legacy,50001));assert.throws(()=>refundAmounts(legacy,0));
const partial={id:'d',status:'RESOLVED',resolution:'PARTIAL_REFUND'};
assert.equal(adminPayoutApproved([partial],[]),false);assert.equal(adminPayoutApproved([partial],[{note:payoutApprovalMarker('d')}]),true);
const confirmed='2026-10-15T12:00:00Z',deadline=Date.parse(confirmed)+DISPUTE_WINDOW_MS;
const fixtures=[['HELD',null,true,'HELD'],['READY',confirmed,false,'BLOCKED'],['READY',confirmed,true,'READY'],['PAID',confirmed,false,'PAID'],['NOT_READY',null,false,'AWAITING'],['NOT_READY',confirmed,true,'NOT_READY'],['CANCELLED',confirmed,true,'CANCELLED'],['READY',null,true,'AWAITING']];
for(const [payoutStatus,customerConfirmedAt,details,expected] of fixtures)assert.equal(completedPayoutStatus({payment:{payoutStatus},customerConfirmedAt},details,deadline),expected);
assert.equal(completedPayoutStatus({payment:{status:'REFUNDED',payoutStatus:'CANCELLED'}},true),'REFUNDED');
assert.equal(completedPayoutStatus({payment:{payoutStatus:'READY'},disputes:[{status:'OPEN'}]},true),'HELD');
const booking={status:'DELIVERED',customerConfirmedAt:confirmed,payment:{payoutStatus:'READY'},disputes:[]};
assert.equal(disputeDeadline(confirmed),deadline);
assert.equal(disputeDeadline('invalid'),null);
assert.equal(customerCanDispute(booking,deadline-1),true);
assert.equal(customerCanDispute(booking,deadline),false);
assert.equal(customerCanDispute(booking,deadline+1),false);
assert.equal(payoutWindowOpen(booking,[],deadline-1),false);
assert.equal(payoutWindowOpen(booking,[],deadline),true);
assert.equal(completedPayoutStatus(booking,true,deadline-1),'WAITING');
assert.equal(completedPayoutStatus(booking,false,deadline-1),'WAITING');
const approved={...booking,disputes:[{id:'release',status:'RESOLVED',resolution:'RELEASE_PAYOUT'}]};
assert.equal(payoutWindowOpen(approved,[],deadline-1),true);
assert.equal(completedPayoutStatus(approved,false,deadline-1),'BLOCKED');
assert.equal(completedPayoutStatus(approved,true,deadline-1),'READY');
for(const status of ['OPEN','UNDER_REVIEW']){
 const held={...approved,disputes:[...approved.disputes,{id:'other',status}]};
 assert.equal(payoutWindowOpen(held,[],deadline-1),false);
 assert.equal(payoutWindowOpen(held,[],deadline+1),false);
 assert.equal(completedPayoutStatus(held,true,deadline+1),'HELD');
}
const partiallyApproved={...booking,disputes:[partial]};
assert.equal(payoutWindowOpen(partiallyApproved,[],deadline-1),false);
assert.equal(payoutWindowOpen(partiallyApproved,[{note:payoutApprovalMarker('d')}],deadline-1),true);
assert.equal(customerCanDispute({...booking,payment:{payoutStatus:'PAID'}},deadline-1),false);
assert.equal(completedPayoutStatus({...approved,payment:{payoutStatus:'PAID'}},true,deadline-1),'PAID');
assert.equal(payoutWindowOpen({...booking,customerConfirmedAt:null},[],deadline),false);
assert.equal(payoutWindowOpen({...booking,customerConfirmedAt:'invalid'},[],deadline),false);
assert.match(reviewDateLabel(Date.parse('2026-10-15T12:00:00Z')),/13:00/);
assert.match(reviewDateLabel(Date.parse('2026-10-26T12:00:00Z')),/12:00/);
console.log('PASS refund accounting, exact 24-hour boundary, early approval, missing bank details, other disputes, paid status and UK clock changes');
